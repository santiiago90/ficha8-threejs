import assert from 'node:assert/strict';
import * as THREE from 'three';
import RAPIER from '@dimforge/rapier2d-compat';
import { adicionarRigidbody, adicionarBoxCollider, adicionarCircleCollider, handleCollisions } from './src/Scripts/Fisica.js';
import { ScoreManager } from './src/Scripts/ScoreManager.js';
globalThis.window = { addEventListener() {} };
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, String(value)) };
let plays = 0;
globalThis.Audio = class { play() { plays++; return Promise.resolve(); } };
const { Player } = await import('./src/Scripts/Player.js');
const { CoinPickup } = await import('./src/Scripts/CoinPickup.js');
delete globalThis.window;
const text = { textContent: '' };
const score = new ScoreManager(text);
score.start();
assert.equal(ScoreManager.getPoints(), 0);
ScoreManager.addPoints(5);
score.start();
assert.equal(text.textContent, '5');
for (const value of ['-10', 'invalid']) {
  storage.set('score', value); score.start(); assert.equal(ScoreManager.getPoints(), 0);
}
ScoreManager.reset();
await RAPIER.init();
const physics = new RAPIER.World({ x: 0, y: 0 });
const events = new RAPIER.EventQueue(true);
const scene = new THREE.Scene();
const player = new THREE.Mesh(new THREE.PlaneGeometry(1, 1));
scene.add(player); new Player(player);
adicionarRigidbody(physics, player); adicionarBoxCollider(physics, player);
const coin = new THREE.Mesh(new THREE.PlaneGeometry(0.6, 0.6));
scene.add(coin); adicionarCircleCollider(physics, coin, true);
const pickup = new CoinPickup(coin);
pickup.onTriggerEnter(new THREE.Group());
assert.equal(ScoreManager.getPoints(), 0);
assert.equal(physics.colliders.len(), 2);
physics.step(events); handleCollisions(physics, events);
assert.equal(ScoreManager.getPoints(), 10);
assert.equal(text.textContent, '10');
assert.equal(storage.get('score'), '10');
assert.equal(plays, 1);
assert.equal(coin.parent, null);
assert.equal(physics.colliders.len(), 1);
pickup.onTriggerEnter(player);
assert.equal(ScoreManager.getPoints(), 10);
score.start(); assert.equal(ScoreManager.getPoints(), 10);
ScoreManager.reset(); assert.equal(storage.get('score'), '0');
events.free(); physics.free();
console.log('OK: persistência, reset, valores inválidos, sensor Rapier, filtro Player, som, remoção e recolha única.');

